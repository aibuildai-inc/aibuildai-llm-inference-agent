"""Build-time tool: scan plugins/ and generate the startup/_plugin_bundle package.

Embeds all plugin file content (JSON manifests, Markdown skills, etc.) as Python string constants.  The bundle is split across N chunk modules (``startup/_plugin_bundle/_chunk_NN.py``) so that each chunk's Cython-generated ``.c`` stays small enough for gcc to build: the whole bundle as ONE module expands to a ~500 MB ``.c`` that gcc cannot compile, but bounded chunks compile in seconds each.  ``startup/_plugin_bundle/__init__.py`` is an aggregator that imports every chunk and merges them back into one ``PLUGIN_BUNDLE`` dict, so ``from startup._plugin_bundle import PLUGIN_BUNDLE`` resolves unchanged.

release.sh stages this package into the build tree, then scripts/cython_compile_tree.py compiles every chunk (and the aggregator) to native ``.so`` along with the rest of the product.  At runtime, startup/resource_materializer.py writes the constants back to tmpfs as real files for the Claude Agent SDK to read.

Usage (called by release.sh during build_runtime_tree): python scripts/build_plugin_bundle.py <plugins_dir> <output_package_dir>
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

# Direct execution places scripts/ on sys.path, so add this checkout's root before
# importing the runtime enumerator shared with the source-mode launch materialize.
_SOURCE_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_SOURCE_ROOT))

from startup.resource_materializer import build_plugin_bundle  # noqa: E402

# Per-chunk target: start a new chunk once the current one's accumulated content
# reaches this many bytes. 4 MiB of content expands to a ~20 MB ``.c`` that
# gcc -O2 compiles in ~3 s — comfortably inside gcc's near-linear regime, well
# below the super-linear blow-up that made the single ~500 MB ``.c`` (the whole
# bundle in one module) uncompilable.
_CHUNK_TARGET_BYTES = 4 * 1024 * 1024

_MODULE_HEADER = '"""AUTO-GENERATED by scripts/build_plugin_bundle.py — do not edit."""\n\n'


def split_into_chunks(
    bundle: dict[str, dict[str, str]], target_bytes: int
) -> list[dict[str, dict[str, str]]]:
    """Split the bundle's ``(plugin_key, rel_path)`` file entries across chunks.

    The split is at the file-entry granularity, by accumulated content bytes: a single plugin's files may span several chunks. Splitting by plugin key alone cannot bound chunk size whenever one plugin is large, so the finer granularity keeps every chunk's generated ``.c`` inside gcc's near-linear regime regardless of how the content is distributed across plugins. Insertion order from ``build_plugin_bundle`` (sorted marketplace/plugin/relpath) is preserved, so the split is deterministic.
    """
    chunks: list[dict[str, dict[str, str]]] = []
    current: dict[str, dict[str, str]] = {}
    accumulated = 0
    for key, files in bundle.items():
        # Register the key even when it has no files (e.g. an uninitialized
        # plugin submodule) so the merged bundle reproduces ``build_plugin_bundle``
        # exactly. An empty entry materializes nothing at runtime.
        current.setdefault(key, {})
        for rel, content in files.items():
            current.setdefault(key, {})[rel] = content
            accumulated += len(content.encode("utf-8"))
            if accumulated >= target_bytes:
                chunks.append(current)
                current = {}
                accumulated = 0
    if current:
        chunks.append(current)
    return chunks


def write_package(
    bundle: dict[str, dict[str, str]],
    package_dir: Path,
    target_bytes: int = _CHUNK_TARGET_BYTES,
) -> None:
    """Write the ``_plugin_bundle`` package: one ``_chunk_NN.py`` per chunk plus an ``__init__.py`` aggregator exposing the merged ``PLUGIN_BUNDLE``."""
    if package_dir.exists():
        shutil.rmtree(package_dir)
    package_dir.mkdir(parents=True)

    chunks = split_into_chunks(bundle, target_bytes)
    chunk_names = [f"_chunk_{i:02d}" for i in range(len(chunks))]
    for name, chunk in zip(chunk_names, chunks):
        chunk_path = package_dir / f"{name}.py"
        with chunk_path.open("w", encoding="utf-8") as fh:
            # The data dict goes on line 3+ (after the docstring header and a
            # blank line) so Cython's PEP-263 coding-cookie scan, which reads
            # only lines 1-2, never mistakes embedded plugin text (e.g. a
            # markdown "coding: ..." phrase) for the source file's encoding.
            fh.write(_MODULE_HEADER)
            fh.write("CHUNK: dict[str, dict[str, str]] = ")
            fh.write(repr(chunk))
            fh.write("\n")

    init_path = package_dir / "__init__.py"
    with init_path.open("w", encoding="utf-8") as fh:
        fh.write(_MODULE_HEADER)
        for name in chunk_names:
            fh.write(f"from startup._plugin_bundle import {name}\n")
        fh.write("\nPLUGIN_BUNDLE: dict[str, dict[str, str]] = {}\n")
        if chunk_names:
            chunk_list = ", ".join(chunk_names)
            fh.write(f"for _chunk in [{chunk_list}]:\n")
            fh.write("    for _key, _files in _chunk.CHUNK.items():\n")
            fh.write("        PLUGIN_BUNDLE.setdefault(_key, {}).update(_files)\n")
            fh.write("del _chunk, _key, _files\n")

    total_files = sum(len(v) for v in bundle.values())
    total_bytes = sum(len(c.encode("utf-8")) for v in bundle.values() for c in v.values())
    print(
        f"Plugin bundle: {len(bundle)} plugins, {total_files} files, "
        f"{total_bytes:,} content bytes -> {len(chunks)} chunk module(s) in {package_dir}"
    )


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <plugins_dir> <output_package_dir>", file=sys.stderr)
        sys.exit(2)
    plugins_root = Path(sys.argv[1]).resolve()
    package_dir = Path(sys.argv[2]).resolve()
    bundle = build_plugin_bundle(plugins_root)
    write_package(bundle, package_dir)
