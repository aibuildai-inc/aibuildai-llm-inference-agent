"""Build the product prompt and memory modules from their runtime resource readers.

The Conversation distribution carries its own catalog resource.
"""

from __future__ import annotations

import sys
from pathlib import Path

# Direct execution places scripts/ on sys.path, so add this checkout's root
# before importing the runtime builders shared with the source-mode import freeze.
_SOURCE_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_SOURCE_ROOT))

from memory.store import build_memory_bundle  # noqa: E402
from engine.work_unit.agent.prompt import build_prompt_templates  # noqa: E402

_PROMPT_ROOT_REL = Path("engine") / "work_unit" / "agent" / "prompt"
_PROMPT_BUNDLE_REL = _PROMPT_ROOT_REL / "_resource_bundle.py"
_MEMORY_REL = Path("memory")
_MEMORY_BUNDLE_REL = Path("memory") / "_resource_bundle.py"


def write_prompt_bundle(templates: dict[str, str], output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as fh:
        fh.write('"""AUTO-GENERATED by scripts/build_resource_bundle.py — do not edit."""\n\n')
        fh.write("PROMPT_TEMPLATES: dict[str, str] = ")
        fh.write(repr(templates))
        fh.write("\n")
    print(f"Prompt bundle: {len(templates)} templates, {output.stat().st_size:,} bytes")


def write_memory_bundle(bundle: dict, output: Path) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open("w", encoding="utf-8") as fh:
        fh.write('"""AUTO-GENERATED by scripts/build_resource_bundle.py — do not edit."""\n\n')
        fh.write("MEMORY_BUNDLE: dict = ")
        fh.write(repr(bundle))
        fh.write("\n")
    print(
        f"Memory bundle: {len(bundle['tasks'])} tasks, {len(bundle['patterns'])} patterns, "
        f"{len(bundle['task_categories'])} mappings, {output.stat().st_size:,} bytes"
    )


def build(repo_root: Path) -> None:
    templates = build_prompt_templates(repo_root / _PROMPT_ROOT_REL)
    write_prompt_bundle(templates, repo_root / _PROMPT_BUNDLE_REL)
    memory_bundle = build_memory_bundle(repo_root / _MEMORY_REL)
    write_memory_bundle(memory_bundle, repo_root / _MEMORY_BUNDLE_REL)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(f"Usage: {sys.argv[0]} <repo_root>", file=sys.stderr)
        sys.exit(2)
    build(Path(sys.argv[1]).resolve())
